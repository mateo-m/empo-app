// Writes docs/changelog.mdx from CHANGELOG.md. The docs scripts run it before
// Blume, and the output is git-ignored.

const source = await Bun.file("CHANGELOG.md").text();
const keptGroups = ["Features", "Bug Fixes", "Performance", "UI"];
const releaseTag = (version: string) =>
  `https://github.com/mateo-m/empo-app/releases/tag/v${version}`;

type Release = { version: string; date: string; groups: Map<string, string[]> };

const releases: Release[] = [];
let current: Release | undefined;
let group: string | undefined;

for (const line of source.split("\n")) {
  const release = line.match(/^## (\S+) - (\d{4}-\d{2}-\d{2})$/);
  if (release) {
    current = { version: release[1], date: release[2], groups: new Map() };
    releases.push(current);
    group = undefined;
    continue;
  }
  if (line.startsWith("## ")) {
    current = undefined;
    continue;
  }
  const heading = line.match(/^### (.+)$/);
  if (heading) {
    group = heading[1];
    continue;
  }
  if (!current || !group || !line.startsWith("- ")) continue;
  if (!keptGroups.includes(group)) continue;
  const entry = line
    .replace(/ \(\[`[0-9a-f]+`\]\(https:\/\/github\.com\/[^)]+\)\)$/, "")
    .replace(/ \((?:[\w.-]+\/[\w.-]+)?#\d+\)$/, "");
  const entries = current.groups.get(group) ?? [];
  entries.push(entry);
  current.groups.set(group, entries);
}

const sections = releases.map((release) => {
  const parts = [`## ${release.version}`, "", `Released ${release.date}. [Download](${releaseTag(release.version)}).`];
  if (release.groups.size === 0) {
    parts.push("", "A maintenance release with no player-facing change.");
  }
  for (const name of keptGroups) {
    const entries = release.groups.get(name);
    if (!entries) continue;
    // Blume reads ":Union" in "Re:Union" as a directive and drops it.
    parts.push("", `### ${name}`, "", ...entries.map((entry) => entry.replace(/:(?=[A-Za-z])/g, "\\:")));
  }
  return parts.join("\n");
});

const page = `---
title: What's new
description: The player-facing changes in each Empo release, derived from the changelog.
sidebar:
  icon: sparkles
---

{/* Generated by tools/changelog-page.ts from CHANGELOG.md. Do not edit. */}

Each release ships an \`.ipa\` file on the
[Releases page](https://github.com/mateo-m/empo-app/releases). This page lists the features,
the bug fixes, and the performance work in each one. The full
[CHANGELOG.md](https://github.com/mateo-m/empo-app/blob/main/CHANGELOG.md) also lists the
build and documentation work.

${sections.join("\n\n")}
`;

await Bun.write("docs/changelog.mdx", page);
console.log(`docs/changelog.mdx: ${releases.length} releases`);

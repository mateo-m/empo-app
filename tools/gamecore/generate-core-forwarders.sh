#!/bin/sh
# Generate the list of the functions that GameCore.h declares, one
# GAMECORE_FUNCTION or GAMECORE_VOID line each.
#
# Empo and the game process open a core with dlopen and RTLD_LOCAL, so
# the linker cannot resolve a single core name at build time.
# ios/Empo/src/App/AppCoreForwarders.c and
# ios/Empo/GameProcess/GameCoreForwarders.c define the two macros and
# include the list, which gives one forwarder for every function.
#
# Usage:
#   tools/gamecore/generate-core-forwarders.sh
set -eu

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
HEADER="$ROOT/cores/GameCore.h"
OUT="$ROOT/ios/Empo/GameProcess/GameCoreFunctions.h"

[ "$#" -eq 0 ] || {
    echo "generate-core-forwarders: unknown argument $1" >&2
    exit 2
}

[ -f "$HEADER" ] || {
    echo "generate-core-forwarders: $HEADER missing" >&2
    exit 1
}

TMP="$(mktemp "${TMPDIR:-/tmp}/core-functions.XXXXXX")"
trap 'rm -f "$TMP"' EXIT

cat >"$TMP" <<'HEAD'
// Generated by tools/gamecore/generate-core-forwarders.sh from
// cores/GameCore.h. Do not edit by hand.

HEAD
awk -f "$ROOT/tools/gamecore/forwarders.awk" "$HEADER" >>"$TMP"
COUNT="$(grep -c '^GAMECORE_' "$TMP")"
if [ "$COUNT" -lt 40 ]; then
    echo "generate-core-forwarders: only $COUNT functions parsed, refusing" >&2
    exit 1
fi
clang-format -i --style=file:"$ROOT/.clang-format" "$TMP"
mv "$TMP" "$OUT"
trap - EXIT
echo "generate-core-forwarders: wrote $COUNT functions to $OUT"

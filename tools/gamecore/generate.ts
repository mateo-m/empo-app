// Reads the functions of cores/GameCore.h and writes every file that
// repeats them. --check writes nothing, and fails when a file in the
// repository differs from what this script would write.
//
// Usage:
//   bun tools/gamecore/generate.ts [--check]

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const headerPath = "cores/GameCore.h";

interface Parameter {
  type: string;
  name: string;
}

interface CoreFunction {
  returnType: string;
  name: string;
  parameters: Parameter[];
}

// The game process relay sends only these types. A function with a
// pointer, a struct, or a callback needs code of its own in
// GameProcessClient.m and GameProcessService.m.
const relayTypes: Record<string, string> = {
  int: "int",
  float: "float",
  double: "double",
  bool: "BOOL",
  "const char *": "nullable NSString *",
};

// GameProcessClient.m defines these gameprocess_* functions itself.
// killSession does nothing, because the app ends the game process
// instead. setDebugLogPath also sends the process output to the log.
const notRelayed = new Set(["killSession", "setDebugLogPath"]);
// The client keeps the new value for its getter before it sends the call.
const ownClientSide = new Set(["setCheatsEnabled", "setFastForwardMultiplier"]);

function parseParameter(text: string, declaration: string): Parameter {
  const match = text.match(/^(.*?)\s*\b([A-Za-z_]\w*)$/);
  if (!match || match[1] === "") {
    throw new Error(`a parameter has no name in: ${declaration}`);
  }
  return { type: match[1]!, name: match[2]! };
}

function parseHeader(text: string): CoreFunction[] {
  const code = text
    .replace(/\\\n/g, " ")
    .replace(/("(?:\\.|[^"\\\n])*")|\/\*[\s\S]*?\*\/|\/\/.*$/gm, (_, literal) => literal ?? " ")
    .replace(/^\s*#.*$/gm, "")
    .replace(/extern "C"/g, "")
    .replace(/[{}]/g, ";");
  const functions: CoreFunction[] = [];
  for (const raw of code.split(";")) {
    const declaration = raw.replace(/\s+/g, " ").trim();
    if (!/\bgamecore_\w+\s*\(/.test(declaration) || declaration.startsWith("typedef ")) {
      continue;
    }
    const match = declaration.match(/^(.+?)\s*\b(gamecore_\w+)\s*\(([^()]*)\)$/);
    if (!match) {
      throw new Error(`cannot read the declaration: ${declaration}`);
    }
    const list = match[3]!.trim();
    functions.push({
      returnType: match[1]!,
      name: match[2]!.slice("gamecore_".length),
      parameters: list === "void" ? [] : list.split(",").map((part) => parseParameter(part.trim(), declaration)),
    });
  }
  if (functions.length === 0) {
    throw new Error(`no gamecore_* function in ${headerPath}`);
  }
  const names = functions.map((fn) => fn.name);
  const repeated = names.find((name, index) => names.indexOf(name) !== index);
  if (repeated) {
    throw new Error(`${headerPath} declares gamecore_${repeated} twice`);
  }
  return functions;
}

const notice = `// SPDX-License-Identifier: GPL-3.0-only
// Copyright (C) 2026 Mateo M. Additional terms apply: see ADDITIONAL-TERMS.md.

// Generated by tools/gamecore/generate.ts from cores/GameCore.h. Do not
// edit by hand.
`;

function declaredType(type: string, name: string): string {
  return type.endsWith("*") ? `${type}${name}` : `${type} ${name}`;
}

function parameterList(fn: CoreFunction): string {
  return fn.parameters.length === 0 ? "void" : fn.parameters.map((p) => declaredType(p.type, p.name)).join(", ");
}

function forwarderList(functions: CoreFunction[]): string {
  const lines = functions.map((fn) => {
    const params = `(${parameterList(fn)})`;
    const args = `(${fn.parameters.map((p) => p.name).join(", ")})`;
    return fn.returnType === "void"
      ? `GAMECORE_VOID(${fn.name}, ${params}, ${args})`
      : `GAMECORE_FUNCTION(${fn.returnType}, ${fn.name}, ${params}, ${args})`;
  });
  return `${notice}
// AppCoreForwarders.c and GameCoreForwarders.c define the two macros
// and include this list.

// clang-format off
${lines.join("\n")}
// clang-format on
`;
}

function exportList(functions: CoreFunction[]): string {
  const names = functions.map((fn) => `_gamecore_${fn.name}`).sort();
  return `${names.join("\n")}\n`;
}

function isRelayed(fn: CoreFunction): boolean {
  return (
    fn.returnType === "void" && !notRelayed.has(fn.name) && fn.parameters.every((p) => p.type in relayTypes)
  );
}

function selector(fn: CoreFunction): string {
  if (fn.parameters.length === 0) {
    return fn.name;
  }
  return fn.parameters
    .map((p, index) => `${index === 0 ? fn.name : p.name}:(${relayTypes[p.type]})${p.name}`)
    .join(" ");
}

function relayProtocol(relayed: CoreFunction[]): string {
  const methods = relayed.map((fn) => `- (void)${selector(fn)};`);
  return `${notice}
#import <Foundation/Foundation.h>

NS_ASSUME_NONNULL_BEGIN

// Each message runs the gamecore_* function of the same name in the
// game process.
// clang-format off
@protocol EmpoGameCoreRelay
${methods.join("\n")}
@end
// clang-format on

NS_ASSUME_NONNULL_END
`;
}

function relayService(relayed: CoreFunction[]): string {
  const methods = relayed.map((fn) => {
    const args = fn.parameters.map((p) => {
      if (p.type !== "const char *") {
        return p.name;
      }
      return p.name === "path" ? `${p.name}.fileSystemRepresentation` : `${p.name}.UTF8String`;
    });
    return `- (void)${selector(fn)} {
    EmpoGameProcessOnMain(^{
        gamecore_${fn.name}(${args.join(", ")});
    });
}`;
  });
  return `${notice}
#import "GameProcessService.h"

#include "GameCore.h"

// clang-format off
@implementation EmpoGameCoreRelayService

${methods.join("\n\n")}

@end
// clang-format on
`;
}

function relayClient(relayed: CoreFunction[]): string {
  const functions = relayed
    .filter((fn) => !ownClientSide.has(fn.name))
    .map((fn) => {
      const texts = fn.parameters
        .filter((p) => p.type === "const char *")
        .map((p) => `    NSString *${p.name}Text = ${p.name} != NULL ? @(${p.name}) : nil;\n`);
      const message =
        fn.parameters.length === 0
          ? fn.name
          : fn.parameters
              .map((p, index) => {
                const value = p.type === "const char *" ? `${p.name}Text` : p.name;
                return `${index === 0 ? fn.name : p.name}:${value}`;
              })
              .join(" ");
      return `void gameprocess_${fn.name}(${parameterList(fn)}) {
${texts.join("")}    EmpoGameProcessSend(^(id<EmpoGameProcess> process) { [process ${message}]; });
}`;
    });
  return `${notice}
#import "EmpoGameProcessProtocol.h"
#import "GameProcessClient.h"

#include "GameCore.h"

// clang-format off
${functions.join("\n\n")}
// clang-format on
`;
}

const functions = parseHeader(fs.readFileSync(path.join(repoRoot, headerPath), "utf8"));
for (const name of [...notRelayed, ...ownClientSide]) {
  if (!functions.some((fn) => fn.name === name)) {
    throw new Error(`generate.ts names gamecore_${name}, but ${headerPath} does not declare it`);
  }
}
const relayed = functions.filter(isRelayed);
const outputs: Record<string, string> = {
  "ios/Empo/GameProcess/GameCoreFunctions.h": forwarderList(functions),
  "cores/gamecore.exports": exportList(functions),
  "ios/Empo/GameProcess/GameCoreRelay.h": relayProtocol(relayed),
  "ios/Empo/GameProcess/GameCoreRelayService.m": relayService(relayed),
  "ios/Empo/src/App/GameCoreRelayClient.m": relayClient(relayed),
};

const check = process.argv.includes("--check");
const unknown = process.argv.slice(2).find((arg) => arg !== "--check");
if (unknown) {
  console.error(`generate: unknown argument ${unknown}`);
  process.exit(2);
}

const stale: string[] = [];
for (const [file, content] of Object.entries(outputs)) {
  const target = path.join(repoRoot, file);
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : undefined;
  if (current === content) {
    continue;
  }
  if (check) {
    stale.push(file);
  } else {
    fs.writeFileSync(target, content);
    console.log(`generate: wrote ${file}`);
  }
}
if (stale.length > 0) {
  console.error(`generate: these files differ from ${headerPath}. Run bun tools/gamecore/generate.ts.`);
  for (const file of stale) {
    console.error(`  ${file}`);
  }
  process.exit(1);
}
console.log(`generate: ${functions.length} functions, ${relayed.length} sent through the game process relay`);
